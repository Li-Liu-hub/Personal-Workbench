#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Assignment {
    pub day: String,
    pub topic: Topic,
    pub page_id: Option<String>,
}

#[derive(Clone, Debug, Serialize)]
pub struct Record {
    pub assignment: Assignment,
    pub page: Option<crate::library::Page>,
}

#[derive(Clone, Debug)]
pub struct Summary {
    pub day: String,
    pub title: String,
    pub topic: String,
    pub page_id: String,
}
